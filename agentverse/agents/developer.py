from typing import Any, List, Optional
from openai import OpenAI
from langchain.prompts import PromptTemplate
from agentverse.agents import Agent
from agentverse.task import Task


class DeveloperAgentError(Exception):
    """Exception raised by DeveloperAgent for errors during code generation.

    This exception is used to signal failures that occur during the code
    generation process within the DeveloperAgent.

    Attributes:
        message (str): Explanation of the error.
    """
    pass


class DeveloperAgent(Agent):
    """Developer Agent: Responsible for generating code based on structured tasks and requirements.

    The DeveloperAgent utilizes an underlying language model client to translate
    task descriptions and instructions into functional Python code implementations.

    Attributes:
        name (str): The name of the agent.
        description (str): A brief description of the agent's purpose.
        llm_client (Any): The client used for interacting with language models.
    """

    CODE_PROMPT = PromptTemplate(
        input_variables=["instruction"],
        template="Generate Python code based on the following instruction:\n\n{instruction}\n\nReturn only the Python code implementation.",
    )

    def __init__(
        self,
        name: str = "DeveloperAgent",
        description: str = "Generates code implementations based on tasks.",
        llm_client=None,
    ):
        """Initializes the DeveloperAgent instance.

        Args:
            name (str): The name of the agent. Defaults to "DeveloperAgent".
            description (str): Description of the agent. Defaults to "Generates code implementations based on tasks.".
            llm_client (Any, optional): The language model client. Defaults to None.
        """
        super().__init__(name=name, description=description)
        self.llm_client = llm_client

    def _call_llm(self, prompt: str) -> str:
        """Calls the underlying LLM client with the given prompt.

        Sends the formatted prompt to the configured LLM client and returns the
        generated response. If no client is configured or if an exception occurs
        during the call, a fallback stub implementation or comment is returned.

        Args:
            prompt (str): The formatted prompt string to send to the LLM.

        Returns:
            str: The raw response string generated by the LLM or a fallback stub/comment.
        """
        if self.llm_client is None:
            return f"# Implementation stub\npass\n"
        
        try:
            return self.llm_client.generate(prompt)
        except Exception:
            return "# TODO: implement based on instruction"

    def generate_code(self, instruction: str) -> str:
        """Generates Python code based on a provided instruction string.

        Formats the instruction using the predefined code generation prompt template,
        invokes the underlying language model, and returns the cleaned code response.

        Args:
            instruction (str): The instruction or requirement describing the code to generate.

        Returns:
            str: The stripped code response generated by the agent.
        """
        prompt = self.CODE_PROMPT.format(instruction=instruction)
        response = self._call_llm(prompt)
        return response.strip()

    def run(self, task: Task, *args, **kwargs) -> str:
        """Execute code generation for a given task.

        Acts as the primary entry point for executing code generation work assigned
        to the developer agent based on the provided task details.

        Args:
            task (Task): The task object containing instructions and description for code generation.
            *args: Additional positional arguments.
            **kwargs: Additional keyword arguments.

        Returns:
            str: The generated code implementation.
        """
        return self.generate_code(task.description)
