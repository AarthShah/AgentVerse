from agentverse.agents.developer import DeveloperAgent
from agentverse.agents.manager import ManagerAgent
from agentverse.agents.research import ResearchAgent
from agentverse.agents.security import SecurityAgent
from agentverse.agents.testing import TestingAgent
from agentverse.llm import get_llm_client
from agentverse.message import TaskMessage
from agentverse.task import Task

def main():
    print("AgentVerse is starting...")

    # Instantiate the ResearchAgent and analyze requirements
    llm_client = get_llm_client()
    researcher = ResearchAgent(
        name="Researcher",
        description="Analyzes project requirements and user stories.",
        llm_client=llm_client,
        user_stories=[
            "As a user, I want to securely log in with my username and password.",
            "As a user, I want to retrieve my account profile data via an API endpoint."
        ]
    )

    print("Analyzing project requirements and user stories...")
    analyzed_tasks = researcher.analyze_requirements()
    print(f"Generated tasks from requirements: {analyzed_tasks}")

    # Instantiate the ManagerAgent and DeveloperAgent for communication demo
    manager = ManagerAgent(name="Manager", description="Manages task orchestration and agent assignment.")
    developer = DeveloperAgent(name="Developer", description="Generates code based on structured tasks.", llm_client=llm_client)

    print("\nDemonstrating basic agent communication...")
    task_message = TaskMessage(sender="Manager", recipient="Developer", task=task1)
    manager.send_message(developer, task_message)
    
    print("Processing inbox for Manager...")
    manager.process_inbox()
    print("Processing inbox for Developer...")
    developer.process_inbox()

    # Instantiate the TestingAgent
    testing_agent = TestingAgent(name="Tester", description="Generates test cases for given code.", llm_client=llm_client)

    # Instantiate the SecurityAgent
    security_agent = SecurityAgent(name="Security", description="Performs vulnerability scans.", llm_client=llm_client)

    # Create sample tasks
    task1 = Task(task_id="1", description="Develop user authentication module.")
    task2 = Task(task_id="2", description="Implement API endpoints for data retrieval.")
    task3 = Task(task_id="3", description="Write unit tests for the authentication module.")
    task4 = Task(task_id="4", description="Set up CI/CD pipeline.")

    sample_tasks = [task1, task2, task3, task4]

    # Orchestrate the tasks and demonstrate LLM reasoning integration
    print("\nOrchestrating tasks...")
    manager.orchestrate_task(sample_tasks)

    print("\nExecuting sample task with LLM reasoning...")
    result = manager.run(task1)
    print(f"LLM-generated output for task '{task1.description}':")
    print(result)

    # Demonstrate TestingAgent
    print("\nGenerating test cases for the authentication module...")
    # In a real scenario, 'result' would contain the code generated by a DeveloperAgent
    # For demonstration, we use a placeholder code snippet.
    placeholder_code = """
def authenticate_user(username, password):
    # Placeholder for authentication logic
    if username == "admin" and password == "password123":
        return True
    return False
"""
    test_cases = testing_agent.generate_test_cases(placeholder_code)
    print("Generated test cases:")
    print(test_cases)

    # Demonstrate SecurityAgent
    print("\nScanning code for vulnerabilities...")
    scan_results = security_agent.scan_for_vulnerabilities(placeholder_code)
    print("Security scan results:")
    print(scan_results)

    print("Task orchestration complete.")

if __name__ == "__main__":
    main()
